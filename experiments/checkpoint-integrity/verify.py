"""Independently recheck exported complete GPU traces, final state and timing."""
import hashlib
import json
from pathlib import Path
import re
import sys
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
EVIDENCE=ROOT/'experiments/checkpoint-integrity/evidence'
ACTUAL=ROOT/'.cache/checkpoint-integrity/actual-20261030a'


def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    def read(path):return json.loads(path.read_text(encoding='utf-8-sig'))
    assert read(ACTUAL/'sequence.json')['complete']
    mutation=read(ACTUAL/'mutations/report.json')
    assert mutation['none']==dict(token_mismatches=0,first=None,final_ram_equal=True,final_registers_equal=True)
    assert len(mutation)==8 and all(v.get('rejected_at_restore') for k,v in mutation.items() if k!='none')
    results={}
    for name,fixture in [('scalar','neural-stories'),('ndot','ndot5-20261030')]:
        inputs=ROOT/'.cache/tiny-llm'/fixture
        directory=ACTUAL/name
        ref=read(inputs/'reference.json');gpu=read(directory/'report.json')
        assert gpu['complete'] and gpu['halted'] and gpu['mismatches']==0
        expected=np.memmap(inputs/'reference.tokens.u32',mode='r',dtype='<u4')
        actual=np.memmap(directory/'actual.tokens.u32',mode='r',dtype='<u4')
        assert len(actual)==len(expected)==ref['tokens']
        for begin in range(0,len(actual),65536):
            assert np.array_equal(actual[begin:begin+65536],expected[begin:begin+65536]),begin
        assert sha(directory/'actual.tokens.u32')==sha(inputs/'reference.tokens.u32')==ref['sha256']
        assert sha(inputs/'engine.elf')==ref['elf_sha256']
        assert (directory/'actual-ram.bin').read_bytes()==(inputs/'reference-ram.bin').read_bytes()
        regs=read(directory/'actual-registers.json')
        assert len(regs)==3 and all(r==ref['final_registers'] for r in regs.values())
        # Decode actual generated BYTE tokens independently of the worker's output file.
        sys.path.insert(0,str(inputs/'reference-package'))
        from chipformer.rv import spec
        base,size=spec.FAMILIES['BYTE']
        raw=(actual[(actual>=base)&(actual<base+min(size,256))]-base).astype('u1').tobytes()
        assert raw==(directory/'actual-output.bin').read_bytes()==(inputs/'reference-output.bin').read_bytes()
        records=[list(map(int,m)) for m in re.findall(rb'^@(\d+) (\d+) (\d+) (\d+) (\d+)\n',raw,re.M)]
        ids=[record[2] for record in records]
        assert len(ids)==ref['steps']==5 and ref['prompt_tokens']==[1,403]
        for path,digest in gpu['scripts'].items():assert sha(ROOT/path.replace('\\','/'))==digest,path
        prefix=read(directory/'prefix-report.json');restore=read(directory/'restore-report.json')
        assert prefix['started_from_checkpoint_offset']==0
        assert prefix['generated_tokens']==restore['started_from_checkpoint_offset']==65536
        assert restore['generated_tokens']==65792
        recovery_offsets=[65536,65792]
        if gpu['started_from_checkpoint_offset']!=65792:
            failure=read(directory/'full-initial-failure-report.json')
            assert name=='scalar' and failure['error']=="KeyError('final_registers')"
            assert failure['started_from_checkpoint_offset']==65792
            assert gpu['started_from_checkpoint_offset']==ref['tokens']
            recovery_offsets.append(ref['tokens'])
        last=0;seconds=0.;chunks=0
        for line in (directory/'chunks.jsonl').read_text().splitlines():
            chunk=json.loads(line);end=chunk['end_offset']
            assert end-last==chunk['amount'] and chunk['compute_seconds']>=seconds
            assert hashlib.sha256(actual[last:end].tobytes()).hexdigest()==chunk['sha256']
            last=end;seconds=chunk['compute_seconds'];chunks+=1
        assert last==len(expected) and seconds==gpu['compute_seconds']
        assert gpu['network_weight_sha256']=='0e515bbb3109997a130c903deb40dce3447f8991e15b6637e0071c71f8b6e07d'
        assert gpu['constructor']==prefix['constructor']==restore['constructor']
        assert gpu['stock_hf'] is False
        for stage in ['prefix','restore','full']:assert read(ACTUAL/f'{name}-{stage}.exit.json')['exit_code']==0
        result=dict(tokens=len(actual),generation_seconds=seconds,tokens_per_second=len(actual)/seconds,
            minutes_per_position=seconds/ref['steps']/60,positions=ref['steps'],prompt_tokens=ref['prompt_tokens'],
            prediction_ids=ids,output=raw.decode(),mismatches=0,final_ram_bytes_exact=65536,final_register_copies_exact=3,
            trace_sha256=sha(directory/'actual.tokens.u32'),elf_sha256=ref['elf_sha256'],
            network_weight_sha256=gpu['network_weight_sha256'],constructor=gpu['constructor'],
            checkpoint_restore_offsets=recovery_offsets,timed_chunks_verified=chunks,
            source_bindings=gpu['scripts'])
        results[name]=result
        (EVIDENCE/f'{name}-run.json').write_text(json.dumps(gpu,indent=2)+'\n')
    assert results['scalar']['prediction_ids']==results['ndot']['prediction_ids']
    assert results['scalar']['output']==results['ndot']['output']
    assert results['scalar']['constructor']==results['ndot']['constructor']
    assert sha(ROOT/'.cache/tiny-llm/neural-stories/model.bin')==sha(ROOT/'.cache/tiny-llm/ndot5-20261030/model.bin')
    report=dict(status='pass',scope='One complete run per binary, both from boot on the unified W=4 compiled Qwen3.5-architecture network through the compact fused executor. Bounded stock checks are separate, not complete runs.',
        timer='Successful generation calls including graph replay, feedback, synchronization, token copies and CPU transfer; excluding setup, validation, IO, checkpoint/restart gaps.',
        model_sha256=sha(ROOT/'.cache/tiny-llm/neural-stories/model.bin'),runs=results,
        validation_recovery=read(EVIDENCE/'scalar-reference-repair.json'),
        scalar_over_ndot_generation_ratio=results['scalar']['generation_seconds']/results['ndot']['generation_seconds'])
    (EVIDENCE/'controlled-measurement.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({name:{k:v for k,v in result.items() if k in ('tokens','generation_seconds','tokens_per_second','minutes_per_position','prediction_ids')} for name,result in results.items()},indent=2))
    print('scalar / NDOT generation time:',report['scalar_over_ndot_generation_ratio'])


if __name__=='__main__':main()
